let currentLanguage = 'en';

// Toggle language function
function toggleLanguage() {
    currentLanguage = currentLanguage === 'en' ? 'es' : 'en';
    updateLanguage();
    localStorage.setItem('language', currentLanguage);
}

// Update all text based on language
function updateLanguage() {
    const elements = document.querySelectorAll('[id]');
    elements.forEach(element => {
        const key = element.id;
        if (translations[currentLanguage][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[currentLanguage][key];
            } else if (element.tagName === 'SELECT') {
                element.options[0].text = translations[currentLanguage][key];
            } else {
                element.textContent = translations[currentLanguage][key];
            }
        }
    });
}

// Smooth scroll to contact section
function scrollToContact() {
    const contactSection = document.getElementById('contact');
    contactSection.scrollIntoView({ behavior: 'smooth' });
}

// Form submission
document.getElementById('contactForm').addEventListener('submit', function(e) {
    e.preventDefault();
    
    const formData = {
        name: document.getElementById('name').value,
        email: document.getElementById('email').value,
        phone: document.getElementById('phone').value,
        business: document.getElementById('business').value,
        interest: document.getElementById('interest').value,
        message: document.getElementById('message').value,
        timestamp: new Date().toISOString()
    };
    
    // Save to localStorage (in production, send to backend)
    let leads = JSON.parse(localStorage.getItem('adobetec_leads')) || [];
    leads.push(formData);
    localStorage.setItem('adobetec_leads', JSON.stringify(leads));
    
    // Show success message
    const submitBtn = document.getElementById('submit-btn');
    const originalText = submitBtn.textContent;
    submitBtn.textContent = currentLanguage === 'en' ? '✓ Submitted!' : '✓ ¡Enviado!';
    submitBtn.style.background = '#4caf50';
    
    setTimeout(() => {
        submitBtn.textContent = originalText;
        submitBtn.style.background = '';
        document.getElementById('contactForm').reset();
    }, 3000);
    
    // Log to console
    console.log('Lead captured:', formData);
});

// Load saved language on page load
window.addEventListener('load', function() {
    const savedLanguage = localStorage.getItem('language');
    if (savedLanguage) {
        currentLanguage = savedLanguage;
        updateLanguage();
    }
});